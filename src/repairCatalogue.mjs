/** @param {string} brandId @param {string} name */
export function repairModelSeries(brandId,name) {
  if (brandId === 'iphone') {
    if (name.includes('SE')) return 'iPhone SE';
    if (name.includes('Air') || name.includes('Duo')) return 'Air & Duo';
    const number=name.match(/^iPhone (1[1-8])/);
    if (number) return 'iPhone '+number[1];
    return 'iPhone X & earlier';
  }
  if (brandId === 'samsung') {
    if (name.startsWith('Galaxy A')) return 'Galaxy A';
    if (name.includes('Fold') || name.includes('Flip')) return 'Galaxy Z / Fold';
    if (name.includes('Note')) return 'Galaxy Note';
    return 'Galaxy S';
  }
  if (name.includes('Fold')) return 'Pixel Fold';
  if (/Pixel (?:[6-9]|10)a/.test(name) || name.includes('3a') || name.includes('4a') || name.includes('5a')) return 'Pixel a series';
  const number=name.match(/^Pixel (11|10|9|8|7|6)/);
  return number ? 'Pixel '+number[1] : 'Pixel 5 & earlier';
}
